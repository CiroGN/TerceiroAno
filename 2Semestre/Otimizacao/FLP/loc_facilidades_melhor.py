def plot_solution(instance, open_facilities_mask, assignments, total_cost):
    plt.figure(figsize=(10, 8))

    # Plota Clientes e linhas de conexão
    # Cores para cada facilidade para diferenciar os clusters
    colors = plt.cm.get_cmap('tab20', instance.num_facilities)

    # Desenhar linhas primeiro (para ficarem no fundo)
    for c_idx, fac_id_assigned in enumerate(assignments):
        if fac_id_assigned != -1:
            client = instance.clients[c_idx]
            # Achar a facilidade correspondente (lembrando que fac_id é 1-based)
            facility = next(f for f in instance.facilities if f['id'] == fac_id_assigned)

            plt.plot([client['x'], facility['x']], [client['y'], facility['y']],
                     color='lightgray', linewidth=0.5, zorder=1)

    # Plota Clientes
    for c in instance.clients:
        plt.scatter(c['x'], c['y'], c='blue', s=20, alpha=0.6, zorder=2, label='Cliente' if c['id']==1 else "")

    # Plota Facilidades
    legend_added_open = False
    legend_added_closed = False

    for i, f in enumerate(instance.facilities):
        is_open = open_facilities_mask[i] == 1
        if is_open:
            plt.scatter(f['x'], f['y'], c='red', marker='D', s=100, edgecolors='black', zorder=3,
                        label='Facilidade Aberta' if not legend_added_open else "")
            # Adiciona ID da facilidade
            plt.text(f['x'], f['y']+2, str(f['id']), fontsize=9, fontweight='bold', color='darkred')
            legend_added_open = True
        else:
            plt.scatter(f['x'], f['y'], c='gray', marker='x', s=50, alpha=0.5, zorder=2,
                        label='Facilidade Fechada' if not legend_added_closed else "")
            legend_added_closed = True

    plt.title(f"Solução FLP - Custo Total: {total_cost:.2f}")
    plt.xlabel("Coordenada X")
    plt.ylabel("Coordenada Y")
    plt.legend(loc='upper right')
    plt.grid(True, linestyle='--', alpha=0.5)

    # Salva ou mostra
    plt.tight_layout()
    plt.show()

